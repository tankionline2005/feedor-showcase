/** The open section's welcome cards: a carousel — swipe or «Далее», dots under it, «Продолжить» at the end. */
export function IntroHost() {
  const key = useOpenIntro()
  const me = useMe()
  const [index, setIndex] = useState(0)
  const [dir, setDir] = useState(1)
  const content = key ? slidesFor(key, me) : null

  useEffect(() => {
    if (key) {
      setIndex(0)
      setDir(1)
    }
  }, [key])

  const count = content?.slides.length ?? 0
  const last = index === count - 1
  const go = (to: number) => {
    if (to < 0 || to >= count) return
    setDir(to > index ? 1 : -1)
    setIndex(to)
  }
  const slide = content?.slides[index]

  return (
    <Sheet
      open={key !== null}
      onClose={closeIntro}
      title={content?.section}
      right={
        !last && (
          <button className="nav-button intro-skip" onClick={closeIntro}>
            Пропустить
          </button>
        )
      }
    >
      {content && slide && (
        <div className="intro">
          <div className="intro-stage">
            {/* not initial={false}: it would stop the pictures' loops on the first card, at their last frame */}
            <AnimatePresence custom={dir} mode="popLayout">
              <motion.div
                key={`${key}-${index}`}
                className="intro-slide"
                custom={dir}
                variants={{
                  enter: (d: number) => ({ x: d * 60, opacity: 0 }),
                  center: { x: 0, opacity: 1 },
                  exit: (d: number) => ({ x: d * -60, opacity: 0 }),
                }}
                initial="enter"
                animate="center"
                exit="exit"
                transition={spring}
                drag="x"
                dragConstraints={{ left: 0, right: 0 }}
                dragElastic={0.35}
                onDragEnd={(_, info) => {
                  if (info.offset.x < -60 || info.velocity.x < -400) go(index + 1)
                  else if (info.offset.x > 60 || info.velocity.x > 400) go(index - 1)
                }}
              >
                <IntroArt name={slide.art} />
                <h2 className="intro-title">{slide.title}</h2>
                <p className="intro-text">{slide.text}</p>
              </motion.div>
            </AnimatePresence>
          </div>
          <div className="intro-dots" role="tablist" aria-label="Карточки">
            {content.slides.map((_, i) => (
              <button
                key={i}
                className={`intro-dot${i === index ? ' on' : ''}`}
                role="tab"
                aria-selected={i === index}
                aria-label={`Карточка ${i + 1}`}
                onClick={() => go(i)}
              />
            ))}
          </div>
          <div className="intro-actions">
            <motion.button
              className="button"
              whileTap={{ scale: 0.97 }}
              onClick={() => (last ? closeIntro() : go(index + 1))}
            >
              {last ? 'Продолжить' : 'Далее'}
            </motion.button>
          </div>
        </div>
      )}
    </Sheet>
  )
}
